function parseField(name: string, spec: string): FieldEntry {
  const secret = spec.endsWith('#secret');
  const body = secret ? spec.slice(0, -'#secret'.length) : spec;
  const bang = body.indexOf('!');
  const cls = (bang === -1 ? body : body.slice(0, bang)) as FieldClass;
  const raw = bang === -1 ? null : body.slice(bang + 1);
  let treatment: ErasureTreatment | null = null;
  if (raw === 'pseudonym' || raw === 'pseudonym-email' || raw === 'clear') treatment = { kind: raw };
  else if (raw !== null && raw.startsWith('literal:')) treatment = { kind: 'literal', value: raw.slice('literal:'.length) };
  else if (raw !== null) throw new Error(`unknown erasure treatment "${raw}" for ${name}`);
  if (cls !== 'none' && !(DATA_CATEGORIES as readonly string[]).includes(cls)) {
    throw new Error(`unknown data class "${cls}" for ${name}`);
  }
  return { name, class: cls, treatment, secret };
}

interface TableOptions {
  links: SubjectLinks;
  erasure: ErasureMode;
  why: string;
}

function table(profile: InventoryProfileKey, fields: Record<string, string>, options?: TableOptions) {
  return {
    profile,
    fields: Object.entries(fields).map(([name, spec]) => parseField(name, spec)),
    links: options?.links ?? null,
    erasure: options?.erasure ?? null,
    why: options?.why ?? null,
  };
}

