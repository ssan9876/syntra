/** Every table, by Prisma model name. */
export const DATA_INVENTORY: Readonly<Record<string, TableEntry>> = Object.fromEntries(
  Object.entries(RAW).map(([model, entry]) => [model, { model, ...entry }]),
);

export function inventoryEntry(model: string): TableEntry {
  const entry = DATA_INVENTORY[model];
  if (entry === undefined) throw new Error(`the data inventory has no entry for ${model}`);
  return entry;
}

/** The tables a data-subject search reads: every one that declares links. */
export function subjectLinkedTables(): TableEntry[] {
  return Object.values(DATA_INVENTORY).filter((entry) => entry.links !== null);
}

/** Whether a table holds any personal data at all. */
export function holdsPersonalData(entry: TableEntry): boolean {
  return entry.fields.some((field) => field.class !== 'none');
}

/**
 * A row as an access bundle may carry it: every column the inventory knows,
 * minus credential material. A column the inventory does not know is left out
 * too -- the structural test makes that impossible in a built tree, and a
 * bundle is the wrong place to discover it.
 */
export function projectForBundle(model: string, row: Record<string, unknown>): Record<string, unknown> {
  const entry = inventoryEntry(model);
  const out: Record<string, unknown> = {};
  for (const field of entry.fields) {
    if (field.secret) continue;
    if (Object.prototype.hasOwnProperty.call(row, field.name)) out[field.name] = row[field.name];
  }
  return out;
}
