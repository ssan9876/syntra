/**
 * The data inventory (backlog #69): every column of every table, classified.
 *
 * This file is the machine-readable source of truth for what personal data
 * Syntra holds, why, where it comes from, how long it is kept and what a
 * data-subject erasure does to it. Three things are derived from it rather
 * than written separately, so they cannot drift from each other:
 *
 *  - `docs/privacy/data-inventory.md`, rendered by `renderDataInventory()`
 *    (`pnpm privacy:inventory`; a test fails when the committed file is stale);
 *  - the data-subject SEARCH and ACCESS BUNDLE, which read every table whose
 *    entry declares `links` and leave out every field marked `#secret`;
 *  - the ERASURE, which applies each field's `!treatment` to the linked rows of
 *    a `pseudonymize` table and deletes the linked rows of a `delete` table.
 *
 * `inventory.test.ts` compares this against the Prisma schema: a column added
 * to a model without an entry here fails the build, as does an entry for a
 * column that no longer exists. Classifying a new column is therefore part of
 * adding it, which is the only point at which anybody knows what it holds.
 *
 * FIELD SPEC GRAMMAR: `<class>[!<treatment>][#secret]`
 *
 *   class      `none` (not personal data), or a personal-data category:
 *              identity | contact | hr | authentication | audit | operational
 *   treatment  what an erasure does to the field, on a `pseudonymize` table:
 *              `pseudonym`        -> 'erased-<row id>' (unique, so unique
 *                                    indexes on logins and keys still hold)
 *              `pseudonym-email`  -> 'erased-<row id>@erased.invalid'
 *              `clear`            -> NULL, or the empty value of a required
 *                                    column ('' / {} / [])
 *              `literal:<text>`   -> that text
 *   #secret    credential material: never copied into an access bundle.
 *
 * Legal bases are PLACEHOLDERS. The controller -- the organisation running
 * Syntra, not Syntra -- decides them, and a value in code would look like
 * advice. Each profile says what is typical so the reviewer has something to
 * confirm or replace (backlog #13, #79).
 */

export const DATA_CATEGORIES = ['identity', 'contact', 'hr', 'authentication', 'audit', 'operational'] as const;
export type DataCategory = (typeof DATA_CATEGORIES)[number];
export type FieldClass = DataCategory | 'none';

export type ErasureTreatment =
  | { kind: 'pseudonym' }
  | { kind: 'pseudonym-email' }
  | { kind: 'clear' }
  | { kind: 'literal'; value: string };

export interface FieldEntry {
  name: string;
  class: FieldClass;
  treatment: ErasureTreatment | null;
  /** Credential material: never copied into an access bundle. */
  secret: boolean;
}

/**
 * How a table's rows are found for one data subject. Each list names columns
 * holding an id of that kind:
 *
 *   person      the person's id
 *   user        an id of an account linked to the person
 *   account     an id of one of the person's target-system accounts
 *   operation   an id of one of the person's lifecycle operations
 *   step        an id of a step of one of those operations
 *   any         any of the above, or one of the person's contract ids
 *   identifier  one of the person's email addresses or account logins
 */
export interface SubjectLinks {
  person?: string[];
  user?: string[];
  account?: string[];
  operation?: string[];
  step?: string[];
  any?: string[];
  identifier?: string[];
}
export type LinkKind = keyof SubjectLinks;

/**
 * What an erasure does to a linked table's rows.
 *
 *   pseudonymize  the rows stay; every field with a treatment is rewritten
 *   delete        the rows are deleted (credential and transient state only --
 *                 never a directory object: deactivate, never delete)
 *   retain        the rows stay unchanged, for the reason in `why`
 */
export type ErasureMode = 'pseudonymize' | 'delete' | 'retain';

export interface InventoryProfile {
  title: string;
  purpose: string;
  source: string;
  retention: string;
  legalBasis: string;
  access: string;
}

export interface TableEntry {
  model: string;
  profile: InventoryProfileKey;
  fields: FieldEntry[];
  links: SubjectLinks | null;
  erasure: ErasureMode | null;
  why: string | null;
}

